/// The language of a project-relative path, from its extension or file name.
pub fn for_path(path: &str) -> Option<&'static Lang> {
    let name = path.rsplit('/').next().unwrap_or(path);
    match name {
        "Makefile" | "Dockerfile" => return None,
        "Gemfile" | "Rakefile" => return Some(&RUBY),
        ".bashrc" | ".zshrc" | ".profile" => return Some(&SHELL),
        _ => {}
    }
    let ext = name.rsplit_once('.')?.1.to_ascii_lowercase();
    Some(match ext.as_str() {
        "rs" => &RUST,
        "ts" | "tsx" | "mts" | "cts" => &TYPESCRIPT,
        "js" | "jsx" | "mjs" | "cjs" => &JAVASCRIPT,
        "py" | "pyi" => &PYTHON,
        "go" => &GO,
        "java" => &JAVA,
        "kt" | "kts" => &KOTLIN,
        "scala" | "sc" => &SCALA,
        "cs" => &CSHARP,
        "swift" => &SWIFT,
        "php" => &PHP,
        "c" | "h" => &C,
        "cc" | "cpp" | "cxx" | "hpp" | "hh" | "hxx" | "ipp" | "m" | "mm" => &CPP,
        "rb" | "rake" | "gemspec" => &RUBY,
        "lua" => &LUA,
        "sh" | "bash" | "zsh" => &SHELL,
        "sql" => &SQL,
        "toml" => &TOML,
        "yaml" | "yml" => &YAML,
        "json" | "jsonc" => &JSON,
        "css" | "scss" | "less" => &CSS,
        "html" | "htm" | "xml" | "svg" | "vue" | "svelte" => &HTML,
        _ => return None,
    })
}

pub fn by_id(id: &str) -> Option<&'static Lang> {
    ALL.iter().copied().find(|l| l.id == id)
}

/// Modifiers that may stand between a definition's start and its name in class bodies.
pub fn is_modifier(word: &str) -> bool {
    JVM_MODIFIERS.contains(&word)
}

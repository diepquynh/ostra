//! The language table: comment and string syntax, keywords, and which family's definition and
//! import rules apply. One entry covers a language for display, outline, usages, and imports.

/// Languages that share definition and import rules.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Family {
    Rust,
    Js,
    Python,
    Go,
    /// Java, Kotlin, Scala, C#, Swift, and PHP: classes with members, dotted imports.
    Jvm,
    C,
    Ruby,
    Lua,
    Shell,
    /// Colored for display only: no definitions, no imports.
    Data,
}

#[derive(Debug)]
pub struct Lang {
    pub id: &'static str,
    pub family: Family,
    pub line_comments: &'static [&'static str],
    pub block_comment: Option<(&'static str, &'static str)>,
    pub nested_comments: bool,
    /// String delimiters. A backtick string always spans lines.
    pub quotes: &'static [u8],
    /// A `"` string may span lines.
    pub multiline_strings: bool,
    /// `"""` and `'''` strings.
    pub triple_quotes: bool,
    /// `'` starts a character literal only; Rust lifetimes are handled by the lexer.
    pub keywords: &'static [&'static str],
    pub case_insensitive: bool,
    pub types: &'static [&'static str],
    pub constants: &'static [&'static str],
    /// Characters an identifier may contain besides letters, digits, and `_`.
    pub ident_extra: &'static [u8],
    /// `@name` is an attribute or annotation.
    pub at_attributes: bool,
    /// Definition keywords and the kind of the name after them.
    pub defs: &'static [(&'static str, Def)],
}

/// What a definition keyword introduces.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Def {
    Function,
    Class,
    Enum,
    Interface,
    Type,
    Module,
    Constant,
    Variable,
    Macro,
    /// Rust `impl`, Swift `extension`: a container for the members inside, no new name.
    Impl,
}

impl Lang {
    /// Files of this language join the usages and dependency index.
    pub fn indexed(&self) -> bool {
        self.family != Family::Data
    }

    pub fn is_keyword(&self, word: &str) -> bool {
        if self.case_insensitive {
            self.keywords.iter().any(|k| k.eq_ignore_ascii_case(word))
        } else {
            self.keywords.contains(&word)
        }
    }

    pub fn def(&self, word: &str) -> Option<Def> {
        self.defs.iter().find(|(k, _)| *k == word).map(|(_, d)| *d)
    }
}

